-- 전기요금 계산 함수 검증
--
-- 쓰는 법: Supabase 대시보드 > SQL Editor 에 이 파일을 붙여넣고 Run.
--          판정 칸이 모두 '일치' 여야 한다. 하나라도 '불일치' 면 함수가 틀린 것이다.
--
-- 기준값은 내가 계산한 값이 아니라 한전이 요금표에 직접 인쇄해 둔 계산 예시다.
-- 그래서 이 대조를 통과하면 요율 데이터와 반올림 규칙이 함께 검증된다.
--   · 부가가치세   원미만 4사5입
--   · 전력기반기금 10원미만 절사
--   · 청구금액     10원미만 절사
-- 출처: sources/electricity/2024-01-01_주택용저압.pdf (1쪽)

with 기대값 as (
    select * from (values
        ('① 기타계절 450kWh 저압 1가구',
         7300::numeric, 82285::numeric, 4050::numeric, 2250::numeric,
         95885::numeric, 9589::numeric, 3540::numeric, 109010::numeric,
         450::numeric, '저압', '2024-01-15'::date, 1),
        ('② 기타계절 900kWh 저압 3가구',
         4800::numeric, 136380::numeric, 8100::numeric, 4500::numeric,
         153780::numeric, 15378::numeric, 5680::numeric, 174830::numeric,
         900::numeric, '저압', '2024-01-15'::date, 3)
    ) as t(사례, 기본요금, 전력량요금, 기후환경요금, 연료비조정요금,
           전기요금, 부가가치세, 전력산업기반기금, 청구금액,
           사용량, 전압, 청구월, 가구수)
),
실제 as (
    select e.사례, e as exp_row,
           pricing.calc_residential_bill(e.사용량, e.전압, e.청구월, e.가구수) as got_row
      from 기대값 e
)
select 사례, 항목, 기대, 계산,
       case when 기대 = 계산 then '일치' else '불일치' end as 판정
  from 실제,
       lateral (values
         ('기본요금',         (exp_row).기본요금,         (got_row).기본요금),
         ('전력량요금',       (exp_row).전력량요금,       (got_row).전력량요금),
         ('기후환경요금',     (exp_row).기후환경요금,     (got_row).기후환경요금),
         ('연료비조정요금',   (exp_row).연료비조정요금,   (got_row).연료비조정요금),
         ('전기요금',         (exp_row).전기요금,         (got_row).전기요금),
         ('부가가치세',       (exp_row).부가가치세,       (got_row).부가가치세),
         ('전력산업기반기금', (exp_row).전력산업기반기금, (got_row).전력산업기반기금),
         ('청구금액',         (exp_row).청구금액,         (got_row).청구금액)
       ) as v(항목, 기대, 계산)
 order by 사례, 항목;


-- 계약전력 기반 함수는 한전이 인쇄한 계산 예시가 없다.
-- 그래서 값을 대조하는 대신 '예외 없이 돌아가고 내역 합이 맞는지' 만 확인한다.
-- 일반용(갑)Ⅱ 고압A 선택Ⅰ, 계약 300kW, 여름철, 경/중간/최대 각 10,000kWh.
-- (갑)Ⅰ 은 시간대별이 아니라 계절별 요금이라 이 함수의 대상이 아니다.
-- 실수로 (갑)Ⅰ 을 넣으면 '시간대 요율이 3개가 아니라 0개' 예외가 난다. 그게 맞는 동작이다.
select '일반용(갑)Ⅱ 고압A 선택Ⅰ 300kW 여름철' as 사례, *,
       case when 전기요금 = 기본요금 + 전력량요금 + 기후환경요금 + 연료비조정요금
             and 청구금액 = trunc((전기요금 + 부가가치세 + 전력산업기반기금) / 10) * 10
            then '내역 합 일치' else '내역 합 불일치' end as 판정
  from pricing.calc_demand_bill('일반용전력(갑)Ⅱ', '고압A', '선택Ⅰ', 300,
                                '2025-07-15', 10000, 10000, 10000);


-- ════════════════════════════════════════════════════════════
-- 계절별 요금 함수 (일반용(갑)Ⅰ·산업용(갑)Ⅰ·교육용(갑)·심야전력)
-- ════════════════════════════════════════════════════════════
-- 이 종별에는 한전이 인쇄한 계산 예시가 없다. 그래서 두 가지로 검증한다.

-- (1) 손계산 대조
--     일반용(갑)Ⅰ 저압 100kW 10,000kWh 2026-07 (여름철 132.4원, 기본 6,160원/kW)
--       616,000 + 1,324,000 + 90,000 + 50,000 = 2,080,000
--       부가세 208,000 / 기금 2.7% 56,160 → 청구 2,344,160
with 기대 as (
    select 616000::numeric  as 기본요금,
           1324000::numeric as 전력량요금,
           2080000::numeric as 전기요금,
           208000::numeric  as 부가가치세,
           56160::numeric   as 전력산업기반기금,
           2344160::numeric as 청구금액
),
계산 as (
    select pricing.calc_seasonal_bill('일반용전력(갑)Ⅰ','저압',null,100,'2026-07-15',10000) as got
)
select '일반용(갑)Ⅰ 저압 100kW 10,000kWh' as 사례, 항목, 기대, 계산,
       case when 기대 = 계산 then '일치' else '불일치' end as 판정
  from 기대 e, 계산 c,
       lateral (values
         ('1 기본요금',         e.기본요금,         (c.got).기본요금),
         ('2 전력량요금',       e.전력량요금,       (c.got).전력량요금),
         ('3 전기요금',         e.전기요금,         (c.got).전기요금),
         ('4 부가가치세',       e.부가가치세,       (c.got).부가가치세),
         ('5 전력산업기반기금', e.전력산업기반기금, (c.got).전력산업기반기금),
         ('6 청구금액',         e.청구금액,         (c.got).청구금액)
       ) as v(항목, 기대, 계산)
 order by 항목;


-- (2) 선택Ⅰ/선택Ⅱ 손익분기점 — 요금표 숫자에서 유도한 항등식과 대조
--     고압A 여름철: 선택Ⅰ(기본 7,170 / 전력량 142.6), 선택Ⅱ(기본 8,230 / 전력량 138.6)
--     기본요금 차 1,060원/kW ÷ 전력량요금 차 4.0원/kWh = 265kWh/kW 에서 교차해야 한다.
--     계약 100kW 이므로 26,500kWh 에서 두 선택의 전기요금이 같아야 한다.
with t as (
  select u.사용량,
         (pricing.calc_seasonal_bill('일반용전력(갑)Ⅰ','고압A','선택Ⅰ',100,'2026-07-15',u.사용량)).전기요금 as 선택1,
         (pricing.calc_seasonal_bill('일반용전력(갑)Ⅰ','고압A','선택Ⅱ',100,'2026-07-15',u.사용량)).전기요금 as 선택2
  from (values (26400::numeric),(26500::numeric),(26600::numeric)) u(사용량)
)
select 사용량, 선택1, 선택2, 선택1 - 선택2 as 차액,
       case
         when 사용량 = 26400 and 선택1 < 선택2 then '일치 (선택Ⅰ 유리)'
         when 사용량 = 26500 and 선택1 = 선택2 then '일치 (손익분기점)'
         when 사용량 = 26600 and 선택1 > 선택2 then '일치 (선택Ⅱ 유리)'
         else '불일치'
       end as 판정
from t order by 사용량;


